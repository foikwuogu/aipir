#!/usr/bin/env python3
"""04 - QA report: row counts, label/event counts vs the HAI README, threshold sanity,
streaming-vs-batch equivalence, and named spot checks. Writes data/processed/qa_report.txt
and adds a "qa_checks" section to paper/stats.json.
"""
import json
import os
import sys

import joblib
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "framework"))
from aipir import config as C  # noqa: E402
from aipir.data import load_file  # noqa: E402
from aipir.metrics import runs  # noqa: E402
from aipir.streaming import StreamingScorer  # noqa: E402

OUT = os.path.join(ROOT, "data", "processed")
STATS = os.path.join(ROOT, "paper", "stats.json")
# attack counts published in the HAI README table (github.com/icsdataset/hai, commit 2a814ce)
README_ATTACKS = {("hai-21.03", "test1"): 5, ("hai-21.03", "test2"): 20, ("hai-21.03", "test3"): 8,
                  ("hai-21.03", "test4"): 5, ("hai-21.03", "test5"): 12,
                  ("hai-20.07", "test1"): 28, ("hai-20.07", "test2"): 10}
STREAM_CHECK_SECONDS = 3600


def main():
    stats = json.load(open(STATS))
    qa_in = stats["qa"]
    ev = pd.read_csv(os.path.join(OUT, "events.csv"))
    summ = pd.read_csv(os.path.join(OUT, "metrics_summary.csv"))
    L, checks, fails = [], {}, []
    w = L.append
    w("AIPIR QA REPORT  (generated by code/04_qa.py; read this before trusting any number)")
    w("=" * 88)

    w("\n1. INPUT ROWS AND SENSORS")
    for ver, q in qa_in.items():
        w(f"  {ver}: train rows {q['train_rows']}  fit {q['fit_rows']}  calibrate {q['cal_rows']} "
          f"({q['cal_hours']:.1f} h)")
        w(f"    sensors {q['sensors_total']} total, {q['sensors_used']} used, "
          f"{len(q['sensors_dropped_constant'])} dropped as constant in normal data")
        w(f"    attack-labelled seconds in raw training files: {q['train_label_sum_raw']}; "
          f"excluded rows (labels + 600 s pad): {q['train_rows_excluded']}; normal segments: {q['normal_segments']}")
        w(f"    attack-labelled seconds inside rows USED for fit/calibration: {q['train_label_sum']} (must be 0)")
        if q["train_label_sum"] != 0:
            fails.append(f"{ver} training data contains attack labels")

    w("\n2. ATTACK EVENTS: label runs vs HAI README counts")
    w("   (a README 'attack' may span several label runs, or adjacent attacks may merge into one run)")
    rows = []
    for (ver, f), n_readme in README_ATTACKS.items():
        df = load_file(os.path.join(ROOT, "data", "raw", ver, f"{f}.csv.gz"))
        n_runs = len(runs(df["attack"].to_numpy()))
        rows.append((ver, f, len(df), int(df["attack"].sum()), n_runs, n_readme))
        w(f"  {ver} {f}: {len(df):>7} s, {int(df['attack'].sum()):>6} attack s, "
          f"{n_runs:>3} label runs, README attacks {n_readme:>3}  {'OK' if n_runs == n_readme else 'DIFFERS'}")
    checks["event_count_match"] = {f"{v}|{f}": [r, m] for v, f, _, _, r, m in rows}

    w("\n3. THRESHOLDS (calibrated on normal data only) AND CALIBRATION FALSE-ALARM RATE")
    for ver, q in qa_in.items():
        days = q["cal_hours"] / 24
        for k, t in q["thresholds"].items():
            rate = q["cal_episodes"][k] / days
            w(f"  {ver} {k:10s} threshold {t:10.4f}   calibration episodes {q['cal_episodes'][k]:>2} "
              f"= {rate:.2f}/day (budget {C.FA_BUDGET_PER_DAY}/day)")
            if rate > C.FA_BUDGET_PER_DAY + 1e-9:
                fails.append(f"{ver} {k} exceeds false-alarm budget on calibration data")

    w("\n4. STREAMING SERVICE == BATCH PIPELINE (first hour of HAI 21.03 test2)")
    bundle = joblib.load(os.path.join(ROOT, "models", "aipir_hai2103.joblib"))
    sc = StreamingScorer(bundle)
    df = load_file(os.path.join(ROOT, "data", "raw", "hai-21.03", "test2.csv.gz")).iloc[:STREAM_CHECK_SECONDS]
    online = np.array([sc.update(r)["score"] for r in df.to_dict("records")])
    batch = pd.read_csv(os.path.join(OUT, "scores_hai-21.03_test2.csv.gz"), nrows=STREAM_CHECK_SECONDS)["score_D3"].to_numpy()
    diff = float(np.max(np.abs(online - batch) / np.maximum(np.abs(batch), 1e-3)))
    w(f"  max relative difference over {STREAM_CHECK_SECONDS} s: {diff:.2e}  "
      f"{'OK' if diff < 1e-3 else 'MISMATCH'}")
    checks["stream_batch_max_rel_diff"] = diff
    if diff >= 1e-3:
        fails.append("streaming scorer disagrees with batch scores")

    w("\n5. RESULT SANITY")
    for r in summ.itertuples():
        ok = 0 <= r.precision <= 1 and 0 <= r.recall <= 1 and r.events_detected <= r.events
        if not ok:
            fails.append(f"metric out of range: {r.version} {r.split} {r.detector}")
    d3 = ev[(ev.detector == "D3") & ev.detected]
    w(f"  all metrics within [0,1] and detected <= events: {'OK' if not fails else 'see failures'}")
    w(f"  D3 TTD range over detected events: {d3.ttd_s.min():.0f}-{d3.ttd_s.max():.0f} s (non-negative required)")
    if (d3.ttd_s < 0).any():
        fails.append("negative time-to-detect")

    w("\n6. NAMED SPOT CHECKS - verify each against the HAI CSV by hand")
    w("   Open the file, find start_time, confirm `attack` turns 1 there and the attack_P* column(s) shown.")
    held = ev[(ev.split == "test") & (ev.detector == "D3") & (ev.version == "hai-21.03")].copy()
    picks = []
    if len(held):
        picks += [held.sort_values("duration_s").iloc[0], held.sort_values("duration_s").iloc[-1]]
        det = held[held.detected]
        if len(det):
            picks += [det.sort_values("ttd_s").iloc[0], det.sort_values("ttd_s").iloc[-1]]
        miss = held[~held.detected]
        if len(miss):
            picks.append(miss.iloc[0])
        rng = np.random.default_rng(20261024)
        picks += [held.iloc[i] for i in rng.choice(len(held), size=min(3, len(held)), replace=False)]
    for p in picks:
        w(f"  {p.version} {p.file} event {int(p.event):>2}: {p.start_time} -> {p.end_time} "
          f"({int(p.duration_s)} s) attacked={p.attacked} D3 detected={bool(p.detected)} "
          f"ttd={'' if pd.isna(p.ttd_s) else int(p.ttd_s)} routed={p.get('routed', '')}")
    w("   random picks use seed 20261024")

    w("\n7. FAILURES")
    w("  none" if not fails else "\n".join("  FAIL: " + f for f in fails))
    checks["failures"] = fails
    txt = "\n".join(L) + "\n"
    open(os.path.join(OUT, "qa_report.txt"), "w").write(txt)
    stats["qa_checks"] = checks
    json.dump(stats, open(STATS, "w"), indent=2, default=float)
    print(txt)
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
